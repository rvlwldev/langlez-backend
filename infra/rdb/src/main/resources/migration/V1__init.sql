create table members (
    agreed_marketing_receive boolean not null,
    birth_day date,
    created_at timestamp(6) with time zone,
    id bigint generated by default as identity,
    member_audit_id bigint unique,
    version bigint not null,
    handle varchar(20),
    country varchar(255),
    email varchar(255),
    fcm varchar(255),
    gender varchar(255) not null check (gender in ('MALE','FEMALE','SECRET')),
    image_url varchar(255),
    provider_display_name varchar(255),
    provider_id varchar(255),
    provider_type varchar(255) check (provider_type in ('GOOGLE','APPLE')),
    role varchar(255) check (role in ('MEMBER','PREMIUM','ADMIN')),
    status varchar(255) check (status in ('CREATED','ACTIVE','SUSPENDED','WITHDRAWN')),
    primary key (id),
    constraint UNQ_MEMBER_PROVIDER unique (provider_id, provider_type),
    constraint UNQ_MEMBER_EMAIL unique (email),
    constraint UNQ_MEMBER_HANDLE unique (handle)
);

