create table attachments (
    attached_at timestamp(6) with time zone,
    created_at timestamp(6) with time zone,
    deleted_at timestamp(6) with time zone,
    id bigint generated by default as identity,
    uploader_id bigint not null,
    key varchar(1000),
    source varchar(255),
    source_id varchar(255),
    status varchar(255) check (status in ('PENDING','ATTACHED','DELETED')),
    type varchar(255) check (type in ('IMAGE','VIDEO','AUDIO')),
    primary key (id),
    constraint UNQ_ATTACHMENT_KEY unique (key)
);

create table chat_event_outbox (
    tries integer not null,
    completed_at timestamp(6) with time zone,
    created_at timestamp(6) with time zone,
    failed_at timestamp(6) with time zone,
