package com.langlez.member.contract

/**
 * 회원이 정지됐다. 실시간 채널이 그 회원의 열린 세션을 끊는 신호다.
 *
 * **아웃박스를 타지 않는다.** `MemberCreatedEvent` 등과 달리 카프카로 나가지 않고
 * 같은 인스턴스의 리스너만 받는다. 정지 조치는 즉시 효력이 있어야 하는데 아웃박스는
 * 2초 주기 폴링이고, 인스턴스 간 전파는 수신 측이 레디스 pub/sub 으로 따로 한다.
 * 다른 모듈이 정지 사실을 지속적으로 소비해야 할 일이 생기면 그때 아웃박스에 얹는다.
 *
 * 같은 회원이 정지 → 해제 → 재정지를 반복하면 같은 [id] 로 여러 번 발생한다.
 * 세션을 끊는 건 멱등한 조치라 구분자를 더 싣지 않는다.
 */
data class MemberSuspendedEvent(
    val id: Long,
)
